def failed_methods(improvement: dict | None) -> list[str]:
    """Честный разбор приёмов, которые не дали прироста."""
    if not improvement:
        return []
    rows = [r for r in improvement.get("rows", []) if "ошибка" not in r]
    usable = [r for r in rows if r["имя"] != "A_базовая"]
    harmful = [(r["имя"], r["прирост_f1_на_тесте"]) for r in usable
               if r["прирост_f1_на_тесте"] < 0]
    noisy = [(r["имя"], r["прирост_f1_на_тесте"]) for r in usable
             if 0.0 <= r["прирост_f1_на_тесте"] < 0.05]
    out: list[str] = []
    if harmful:
        out.append(
            "Приёмы, которые себя не оправдали: "
            + "; ".join(f"«{n}» ({d:+.3f})" for n, d in harmful)
            + ". augmentation размывает границу между нормой и отказом, а более "
            "частая сетка окон без других изменений не помогает."
        )
    if noisy:
        out.append(
            "Приёмы с приростом на уровне шума: "
            + "; ".join(f"«{n}» ({d:+.3f})" for n, d in noisy)
            + ". На 62 окнах такие различия неотличимы от случайных."
        )
    return out


def decomposition(improvement: dict | None) -> list[str]:
    """Раскладывает прирост на порядок обучения, порог и архитектуру."""
    if not improvement:
        return []
    ladder = improvement.get("разложение_прироста") or improvement.get("ladder") or []
    if len(ladder) < 5:
        return []
    stages = [step["метрики"] for step in ladder]
    o_half, o_best, r_half, r_best, final = stages[0], stages[1], stages[2], stages[3], stages[4]
    d_order = r_half["f1"] - o_half["f1"]
    d_threshold = r_best["f1"] - r_half["f1"]
    d_architecture = final["f1"] - r_best["f1"]
    out = [
        "Разложение прироста. Прежний порядок обучения при threshold 0.5 даёт F1 "
        f"{_fmt(o_half['f1'])}. Пересмотр порядка обучения поднимает её до "
        f"{_fmt(r_half['f1'])} ({d_order:+.3f}). Подбор threshold при базовой "
        f"архитектуре добавляет {d_threshold:+.3f}, смена архитектуры — ещё "
        f"{d_architecture:+.3f}. Основной вклад дали порядок обучения и "
        "архитектура, а не подбор threshold.",
    ]
    if o_best["f1"] < o_half["f1"]:
        out.append(
            "Показательная деталь про threshold. В прежнем порядке обучения "
            "контроль состоял всего из двух экспериментов, и на них модель "
            "разделяла норму и отказ идеально. Найденный по такому контролю "
            f"threshold {_fmt(o_best['порог'])} на test даёт F1 {_fmt(o_best['f1'])} — "
            f"хуже обычного threshold 0.5 ({_fmt(o_half['f1'])}). Вывод: подбор "
            "threshold полезен ровно настолько, насколько представителен контроль.",
        )
    return out


