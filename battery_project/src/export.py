# --- вспомогательное форматирование ---------------------------------------

def _fmt(v, nd=3):
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return "-"


def _fig(name: str) -> str:
    return f"figures/{name}.png"


def _plural(n: int, one: str, few: str, many: str) -> str:
    """Русская форма числительного: 1 строка / 2 строки / 5 строк."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def _rows_batteries(n_rows: int, n_bat: int) -> str:
    return (f"{n_rows} {_plural(n_rows, 'строка', 'строки', 'строк')}, "
            f"{n_bat} {_plural(n_bat, 'батарея', 'батареи', 'батарей')}")


def _metric_good(v: str) -> str:
    return f'<span class="metric-good">{v}</span>'


def _metric_mid(v: str) -> str:
    return f'<span class="metric-mid">{v}</span>'


def _metric_bad(v: str) -> str:
    return f'<span class="metric-bad">{v}</span>'


def _fmt_metric(v) -> str:
    """MAE/RMSE: 4 знака для |v| < 1, иначе 3."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return "-"
    return f"{f:.4f}" if abs(f) < 1 else f"{f:.3f}"


def _fmt_r2(v) -> str:
    """R²: 4 знака для |R²| < 1, иначе 2."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return "-"
    return f"{f:.4f}" if abs(f) < 1 else f"{f:.2f}"


def _load_processed_json(fname: str) -> dict | None:
    """Чтение JSON из data/processed/; отсутствующий/битый файл → None."""
    path = PROCESSED_DIR / fname
    if not path.exists():
        return None
    try:
        with path.open(encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


